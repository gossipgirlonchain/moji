/** Width of a run of non-emoji text in px. Unknown glyphs count as 0.6em. */
export function measure(text: string, size: number, font: FontMetrics, letterSpacingEm = 0): number {
  let w = 0;
  for (const ch of text) w += font.adv[ch] ?? 0.6;
  return (w + letterSpacingEm * Array.from(text).length) * size;
}
